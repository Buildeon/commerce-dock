/**
 * Commerce Dock: Commerce Pulse & AI Agent Stack Context Engine
 * 
 * Capabilities:
 * 1. AI Agent / MCP Topology Manifest Exporter:
 *    Generates clean, sanitized stack architecture topologies (stack-context.json & Markdown)
 *    for AI operations agents (OpenClaw, Hermes, Claude Code, Antigravity).
 *    STRICT SECURITY GUARANTEE: Never leaks vault credentials, passwords, or secret hints.
 * 
 * 2. Modular Commerce Pulse Adapters:
 *    Lightweight, SSRF-guarded health and telemetry probes for composable commerce backends:
 *    - Medusa (/health)
 *    - Meilisearch (/health)
 *    - Umami (/api/heartbeat)
 *    - Generic HTTP/HTTPS ping
 */

import { CommerceDockSSRF } from './ssrf-validator.js';

class CommerceDockPulse {
  constructor(options = {}) {
    this.allowedHosts = options.allowedHosts || [];
    this.cache = new Map();
  }

  /**
   * Export sanitized stack topology manifest for AI Agent / MCP ingestion.
   * STRICT SECURITY: Recursively strips any credentials, secrets, or hints.
   */
  static exportStackContext(presetData, format = 'json') {
    if (!presetData || !presetData.services) {
      throw new Error('Invalid preset data: services array required');
    }

    const sanitizedServices = presetData.services.map(s => {
      const entry = {
        id: s.id,
        name: s.name,
        category: s.category || 'general',
        badge: s.badge || null,
        url: s.url,
        description: s.description || '',
        status: s.status || 'unknown'
      };

      if (s.subplatforms && Array.isArray(s.subplatforms)) {
        entry.subplatforms = s.subplatforms.map(sp => ({
          name: sp.name,
          url: sp.url,
          description: sp.description || ''
        }));
      }

      // Security check: Never export credentials or hints
      return entry;
    });

    const topology = {
      manifestVersion: '1.0.0',
      schema: 'https://buildeon.solutions/schemas/mcp-stack-context.json',
      generatedAt: new Date().toISOString(),
      dockId: presetData.dockId || 'custom-dock',
      title: presetData.title || 'Composable Commerce Stack',
      brand: presetData.brand?.name || 'Sovereign Merchant',
      totalServices: sanitizedServices.length,
      categories: [...new Set(sanitizedServices.map(s => s.category))],
      services: sanitizedServices
    };

    if (format === 'markdown') {
      return CommerceDockPulse._formatMarkdownTopology(topology);
    }
    return JSON.stringify(topology, null, 2);
  }

  static _formatMarkdownTopology(topology) {
    let md = `# Architecture Topology: ${topology.title}\n`;
    md += `*Generated by Commerce Dock for AI Operations Agents (${topology.generatedAt})*\n\n`;
    md += `**Brand:** ${topology.brand} | **Services:** ${topology.totalServices} | **Categories:** ${topology.categories.join(', ')}\n\n`;
    md += `## Active Fleet Matrix\n\n`;

    for (const service of topology.services) {
      md += `### [${service.name}](${service.url}) (${service.category.toUpperCase()})\n`;
      if (service.badge) md += `*Role:* \`${service.badge}\` · *Status:* \`${service.status}\`\n\n`;
      if (service.description) md += `${service.description}\n\n`;

      if (service.subplatforms && service.subplatforms.length > 0) {
        md += `**Endpoints & Subsystems:**\n`;
        for (const sp of service.subplatforms) {
          md += `- [${sp.name}](${sp.url}): ${sp.description}\n`;
        }
        md += `\n`;
      }
      md += `---\n\n`;
    }

    md += `> **Security Guarantee:** Zero credentials or access tokens are stored in this topology manifest. Master password vaults remain encrypted client-side.\n`;
    return md;
  }

  /**
   * Probe service pulse with SSRF validation
   */
  async probeService(service) {
    if (!service || !service.url) {
      return { online: false, error: 'Service URL missing', latencyMs: -1 };
    }

    // Determine probe URL based on known adapters
    let probeUrl = service.url;
    if (service.id && service.id.includes('medusa')) {
      probeUrl = service.url.replace(/\/+$/, '') + '/health';
    } else if (service.id && service.id.includes('meilisearch')) {
      probeUrl = service.url.replace(/\/+$/, '') + '/health';
    } else if (service.id && service.id.includes('umami')) {
      probeUrl = service.url.replace(/\/+$/, '') + '/api/heartbeat';
    }

    return CommerceDockSSRF.executeSafeHealthCheck(probeUrl, {
      allowedHosts: this.allowedHosts,
      timeoutMs: 4000
    });
  }
}

// Module export for Node.js / test suites, or Window global for browser
if (typeof module !== 'undefined' && module.exports) {
  module.exports = CommerceDockPulse;
}
if (typeof window !== 'undefined') {
  window.CommerceDockPulse = CommerceDockPulse;
}

export { CommerceDockPulse };
export default CommerceDockPulse;
